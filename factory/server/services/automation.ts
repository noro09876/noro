/* ---------------- Schedule math ---------------- */

/** Weekday of a YYYY-MM-DD date, 0 = Sunday … 6 = Saturday. */
function weekday(date: string) {
  const [y, m, d] = date.split('-').map(Number) as [number, number, number];
  return new Date(Date.UTC(y, m - 1, d)).getUTCDay();
}

export function nextRunAt(c: RuleConfig, after: Date): Date | null {
  const today = formatInTz(after, c.schedule.timezone).date;
  for (let i = 0; i < 8; i++) {
    const date = addDays(today, i);
    if (!c.schedule.weekdays.includes(weekday(date))) continue;
    const at = zonedToUtc(date, c.schedule.time, c.schedule.timezone);
    if (at > after) return at;
  }
  return null;
}

/* ---------------- CRUD ---------------- */

export function normalizeConfig(input: Partial<RuleConfig>): RuleConfig {
  return {
    schedule: { ...DEFAULT_RULE.schedule, ...input.schedule },
    generate: { ...DEFAULT_RULE.generate, ...input.generate },
    approval: { ...DEFAULT_RULE.approval, ...input.approval },
    publish: { ...DEFAULT_RULE.publish, ...input.publish },
    onError: { ...DEFAULT_RULE.onError, ...input.onError },
    limits: { ...DEFAULT_RULE.limits, ...input.limits },
  };
}

/**
 * Saves a rule. Turning on a rule that creates or schedules a lot of content without
 * human approval requires an explicit confirmation (`confirmed`).
 */
export async function saveRule(workspaceId: string, userId: string, input: { id?: string; brandId: string; name: string; enabled: boolean; config: Partial<RuleConfig>; confirmed?: boolean }) {
  const cfg = normalizeConfig(input.config);
  const errs = validateRule(cfg);
  if (errs.length) throw badRequest(errs.join('. '), { errors: errs });
  const brand = await getBrand(input.brandId);
  if (brand.workspaceId !== workspaceId) throw notFound('Бренд');
  const risky = input.enabled && (!cfg.approval.required || cfg.generate.itemsPerRun * cfg.limits.maxRunsPerDay > cfg.limits.requireConfirmAbove);
  if (risky && !input.confirmed) {
    throw new AppError(428, 'confirm_required', !cfg.approval.required ? 'Правило будет планировать публикации без согласования человеком. Подтвердите включение.' : `Правило создаёт больше ${cfg.limits.requireConfirmAbove} материалов в день. Подтвердите включение.`);
  }
  const values = { workspaceId, brandId: input.brandId, name: input.name.trim() || 'Правило', enabled: input.enabled, config: cfg, nextRunAt: input.enabled ? nextRunAt(cfg, new Date()) : null, status: input.enabled ? 'idle' : 'off', pausedReason: null, consecutiveFailures: 0, updatedAt: new Date() };
  const [row] = input.id
    ? await db.update(schema.automationRules).set(values).where(and(eq(schema.automationRules.id, input.id), eq(schema.automationRules.workspaceId, workspaceId))).returning()
    : await db.insert(schema.automationRules).values(values).returning();
  if (!row) throw notFound('Правило');
  await audit({ workspaceId, actorType: 'user', actorId: userId, action: input.id ? 'rule.updated' : 'rule.created', entityType: 'rule', entityId: row.id, message: `Правило «${row.name}» ${row.enabled ? 'включено' : 'сохранено выключенным'}${risky ? ' (с подтверждением)' : ''}` });
  return row;
}

/* ---------------- Running ---------------- */

async function itemsCreatedToday(rule: RuleRow): Promise<number> {
  const since = zonedToUtc(formatInTz(new Date(), rule.config.schedule.timezone).date, '00:00', rule.config.schedule.timezone);
  const [r] = await db
    .select({ n: sql<number>`count(*)::int` })
    .from(schema.contentItems)
    .innerJoin(schema.campaigns, eq(schema.campaigns.id, schema.contentItems.campaignId))
    .where(and(eq(schema.campaigns.ruleId, rule.id), gte(schema.contentItems.createdAt, since)));
  return r?.n ?? 0;
}

/** One run: a small campaign whose strategy and items are generated by the normal pipeline. */
export async function runRule(rule: RuleRow, opts: { manual?: boolean; userId?: string } = {}) {
  const c = rule.config;
  const tz = c.schedule.timezone;
  const today = formatInTz(new Date(), tz).date;
  const runsToday = rule.runsDay === today ? rule.runsToday : 0;
  if (runsToday >= c.limits.maxRunsPerDay) {
    await audit({ workspaceId: rule.workspaceId, actorType: 'worker', action: 'rule.skipped', entityType: 'rule', entityId: rule.id, level: 'warn', message: `«${rule.name}»: дневной лимит запусков (${c.limits.maxRunsPerDay}) исчерпан` });
    return null;
  }
  const allowance = c.limits.maxItemsPerDay - (await itemsCreatedToday(rule));
  const count = Math.min(c.generate.itemsPerRun, allowance);
  if (count < 1) {
    await audit({ workspaceId: rule.workspaceId, actorType: 'worker', action: 'rule.skipped', entityType: 'rule', entityId: rule.id, level: 'warn', message: `«${rule.name}»: дневной лимит материалов (${c.limits.maxItemsPerDay}) исчерпан` });
    return null;
  }
  const [camp] = await db
    .insert(schema.campaigns)
    .values({
      workspaceId: rule.workspaceId,
      brandId: rule.brandId,
      title: `${rule.name} · ${today}`,
      ruleId: rule.id,
      createdBy: opts.userId ?? null,
      brief: {
        task: c.generate.topicHint || 'Регулярные публикации бренда по стратегии',
        audience: '',
        goal: 'Регулярное присутствие бренда в соцсетях',
        platforms: c.generate.platforms,
        formats: c.generate.formats,
        frequency: count,
        constraints: `Ровно ${count} материал(а) за запуск.`,
        startDate: today,
        weeks: 1,
        timezone: tz,
      },
    })
    .returning();
  await db
    .update(schema.automationRules)
    .set({ lastRunAt: new Date(), runsToday: runsToday + 1, runsDay: today, status: 'running', nextRunAt: nextRunAt(c, new Date()), updatedAt: new Date() })
    .where(eq(schema.automationRules.id, rule.id));
  await enqueue(Q.strategy, { campaignId: camp!.id }, { singletonKey: `strategy:${camp!.id}` });
  await audit({ workspaceId: rule.workspaceId, actorType: opts.userId ? 'user' : 'worker', actorId: opts.userId, action: 'rule.run', entityType: 'rule', entityId: rule.id, message: `«${rule.name}»: запуск${opts.manual ? ' вручную' : ' по расписанию'} — ${count} материал(а)` });
  return camp!;
}

export async function runDueRules(now = new Date()) {
  const rules = await db.select().from(schema.automationRules).where(and(eq(schema.automationRules.enabled, true), isNotNull(schema.automationRules.nextRunAt), lte(schema.automationRules.nextRunAt, now)));
  for (const r of rules) {
    try {
      await runRule(r);
    } catch (e) {
      logger.error({ err: e, rule: r.id }, 'automation run failed');
      await ruleFailure(r.id, (e as Error).message);
    }
    // Always move the schedule forward so a failing rule doesn't loop every minute.
    await db.update(schema.automationRules).set({ nextRunAt: nextRunAt(r.config, now) }).where(eq(schema.automationRules.id, r.id));
  }
  return rules.length;
}

async function ruleFailure(ruleId: string, message: string) {
  const [r] = await db
    .update(schema.automationRules)
    .set({ consecutiveFailures: sql`${schema.automationRules.consecutiveFailures} + 1`, status: 'error', updatedAt: new Date() })
    .where(eq(schema.automationRules.id, ruleId))
    .returning();
  if (!r) return;
  if (r.consecutiveFailures >= r.config.limits.pauseAfterFailures) {
    await db.update(schema.automationRules).set({ enabled: false, status: 'paused', pausedReason: `Остановлено после ${r.consecutiveFailures} ошибок подряд: ${message}`, nextRunAt: null }).where(eq(schema.automationRules.id, ruleId));
    await audit({ workspaceId: r.workspaceId, actorType: 'worker', action: 'rule.paused', entityType: 'rule', entityId: r.id, level: 'error', message: `«${r.name}» остановлено после ${r.consecutiveFailures} ошибок подряд` });
  }
}

async function ruleOf(campaignId: string): Promise<RuleRow | null> {
  const camp = await getCampaign(campaignId);
  if (!camp.ruleId) return null;
  const [r] = await db.select().from(schema.automationRules).where(eq(schema.automationRules.id, camp.ruleId));
  return r ?? null;
}

/** Strategy outcome of a rule-created campaign. */
export async function onStrategyOutcome(campaignId: string, ok: boolean, message = '') {
  const rule = await ruleOf(campaignId);
  if (!rule) return;
  if (ok) await db.update(schema.automationRules).set({ consecutiveFailures: 0, status: 'idle' }).where(eq(schema.automationRules.id, rule.id));
  else await ruleFailure(rule.id, message);
}

/** After quality checks: rule items go to review, or are auto-approved when the rule allows it. */
export async function onItemChecked(itemId: string, passed: boolean) {
  const item = await getItem(itemId);
  const rule = await ruleOf(item.campaignId);
  if (!rule || item.status !== 'ready') return;
  if (!passed) {
    await audit({ workspaceId: item.workspaceId, actorType: 'worker', action: 'rule.item_blocked', entityType: 'item', entityId: itemId, level: 'warn', message: `«${item.title.slice(0, 60)}» не прошёл проверку — автоматизация остановила его до правки` });
    return;
  }
  const { decide, requestReview } = await import('./review');
  if (rule.config.approval.required) await requestReview(item.workspaceId, itemId, null);
  else await decide(item.workspaceId, itemId, 'approved', null, { userId: null, automatic: `Автоматически по правилу «${rule.name}»: согласование не требуется` });
}

/** After approval: rule items are scheduled into the rule's free slots. */
export async function onItemApproved(itemId: string) {
  const item = await getItem(itemId);
  const rule = await ruleOf(item.campaignId);
  if (!rule || rule.config.publish.mode !== 'schedule_after_approval') return;
  const { preparePosts, findConflicts, schedulePost } = await import('./posts');
  const platforms = (item.platforms as PlatformId[]).filter((p) => rule.config.generate.platforms.includes(p));
  const prepared = await preparePosts({ workspaceId: item.workspaceId, itemId, platforms, timezone: rule.config.schedule.timezone });
  const tz = rule.config.schedule.timezone;
  const start = formatInTz(new Date(), tz).date;
  for (const p of prepared) {
    if (!p.post) {
      await audit({ workspaceId: item.workspaceId, actorType: 'worker', action: 'rule.post_skipped', entityType: 'item', entityId: itemId, level: 'warn', message: `«${rule.name}»: ${p.platform} пропущен — ${p.error}` });
      continue;
    }
    if (p.post.status !== 'ready') continue;
    let scheduled = false;
    for (let d = 0; d < 14 && !scheduled; d++) {
      for (const slot of rule.config.publish.slots) {
        const at = zonedToUtc(addDays(start, d), slot, tz);
        if (at.getTime() < Date.now() + 10 * 60_000) continue;
        if ((await findConflicts(p.post, at, rule.config.publish.minGapMinutes)).length) continue;
        try {
          await schedulePost(item.workspaceId, p.post.id, { at: at.toISOString(), timezone: tz }, null);
          scheduled = true;
        } catch (e) {
          await audit({ workspaceId: item.workspaceId, actorType: 'worker', action: 'rule.schedule_failed', entityType: 'post', entityId: p.post.id, level: 'warn', message: `«${rule.name}»: ${(e as Error).message}` });
          d = 14;
        }
        break;
      }
    }
  }
}

export async function rulesOverview(workspaceId: string) {
  const rules = await db.select().from(schema.automationRules).where(eq(schema.automationRules.workspaceId, workspaceId));
  if (!rules.length) return [];
  const camps = await db
    .select({ ruleId: schema.campaigns.ruleId, n: sql<number>`count(*)::int` })
    .from(schema.campaigns)
    .where(inArray(schema.campaigns.ruleId, rules.map((r) => r.id)))
    .groupBy(schema.campaigns.ruleId);
  return rules.map((r) => ({ ...r, runs: camps.find((c) => c.ruleId === r.id)?.n ?? 0 }));
}
